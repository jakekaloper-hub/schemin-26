'use strict';
const fs=require('fs'), path=require('path'), cp=require('child_process');
const BULLPEN=path.join(process.env.HOME,'Developer/ai/bullpen-runtime');
const PROJECT=path.join(process.env.HOME,'Developer/ai/Schemin_UE_Prototype');
const {compileIntent}=require(path.join(BULLPEN,'runtime/intentCompiler'));
const {routeTask}=require(path.join(BULLPEN,'runtime/router'));
const instruction='/bullpen mission --schemin-26 --unreal --world-engine --atlas --full-lifecycle: continue building the Commonwealth Unreal integration from verified canon, execute local reversible jobs, test, report blockers, no false green and no automatic publication';
const compiled=compileIntent(instruction);
const routing=routeTask(instruction,{material:true,forceCounterweights:true});
const logDir=path.join(PROJECT,'ScheminBridge/generated');
fs.mkdirSync(logDir,{recursive:true});
const receipt={timestamp:new Date().toISOString(),mission:instruction,command:compiled.command,lifecycle:compiled.lifecycle,primary:routing.primary,participants:routing.participants,counterweight_plan:routing.counterweight_plan,host:'local-script',note:'Deterministic routing and pipeline; does not invoke autonomous LLM director staff or generate new tasks.'};
if(compiled.command!=='mission')throw new Error('Bullpen mission command not resolved');
const python='/opt/homebrew/bin/python3';
const result=cp.spawnSync(python,['-m','ScheminBridge.production_runner'],{cwd:PROJECT,encoding:'utf8',timeout:600000});
receipt.exit_code=result.status;
receipt.status=result.status===0?'LOCAL_PIPELINE_PASS_NOT_RELEASED':'BLOCKED';
receipt.stdout=(result.stdout||'').slice(-2000);
receipt.stderr=(result.stderr||'').slice(-2000);
fs.writeFileSync(path.join(logDir,'bullpen_mission_receipt.json'),JSON.stringify(receipt,null,2)+'\n');
console.log('BULLPEN',receipt.command,receipt.primary,receipt.status);
if(result.status!==0)process.exitCode=1;
