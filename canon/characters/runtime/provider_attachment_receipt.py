"""Validate provider-origin image attachment receipts without granting release status.

Transport receipt validation is distinct from generated-image identity QA.
"""
from __future__ import annotations
import re

_HEX64 = re.compile(r"^[0-9a-f]{64}$")
def validate_provider_attachment_receipt(request_id, route, expected_assets, provider_receipt):
    """Fail closed when per-subject provider attachment evidence is absent or swapped.

    expected_assets: list of dictionaries with character_id, sha256, subject_slot.
    provider_receipt: signed/attested evidence from an actual adapter, not a
    preflight payload generated by this repository.
    """
    def blocked(reason):
        return {"state": "RENDERER_REFERENCE_MOUNT_UNVERIFIED", "reason": reason,
                "generation_eligible": False}
    if not isinstance(provider_receipt, dict):
        return blocked("PROVIDER_RECEIPT_REQUIRED")
    if provider_receipt.get("request_id") != request_id or provider_receipt.get("route") != route:
        return blocked("REQUEST_OR_ROUTE_MISMATCH")
    if provider_receipt.get("origin") != "PROVIDER_OBSERVED":
        return blocked("PROVIDER_ORIGIN_UNVERIFIED")
    if not provider_receipt.get("provider_invocation_id") or not provider_receipt.get("provider_evidence_id"):
        return blocked("PROVIDER_INVOCATION_EVIDENCE_REQUIRED")
    if not isinstance(expected_assets, list) or not expected_assets:
        return blocked("EXPECTED_ASSETS_REQUIRED")
    entries = provider_receipt.get("attachments")
    if not isinstance(entries, list) or len(entries) != len(expected_assets):
        return blocked("ATTACHMENT_COUNT_MISMATCH")
    required = ("character_id", "sha256", "subject_slot")
    if any(not isinstance(a, dict) or not all(a.get(k) for k in required) for a in expected_assets):
        return blocked("INVALID_EXPECTED_ASSET")
    ids = [a["character_id"] for a in expected_assets]
    if len(ids) != len(set(ids)):
        return blocked("DUPLICATE_EXPECTED_CHARACTER")
    seen_ids, seen_slots, seen_attachment_ids = set(), set(), set()
    expected_by_id = {a["character_id"]: a for a in expected_assets}
    for entry in entries:
        if not isinstance(entry, dict):
            return blocked("INVALID_ATTACHMENT")
        cid = entry.get("character_id")
        if cid not in expected_by_id or cid in seen_ids:
            return blocked("DUPLICATE_OR_UNKNOWN_CHARACTER")
        expected = expected_by_id[cid]
        if entry.get("subject_slot") != expected["subject_slot"]:
            return blocked("SUBJECT_SLOT_MISMATCH")
        if entry.get("mounted_sha256") != expected["sha256"]:
            return blocked("MOUNTED_BYTE_HASH_MISMATCH")
        if not isinstance(entry.get("mounted_sha256"), str) or not _HEX64.fullmatch(entry["mounted_sha256"]):
            return blocked("MOUNTED_BYTE_HASH_INVALID")
        aid = entry.get("provider_attachment_id")
        binding = entry.get("provider_subject_binding_id")
        if not aid or not binding or not entry.get("provider_binding_observed"):
            return blocked("PROVIDER_SUBJECT_BINDING_UNVERIFIED")
        if aid in seen_attachment_ids or entry["subject_slot"] in seen_slots:
            return blocked("DUPLICATE_ATTACHMENT_OR_SLOT")
        seen_ids.add(cid)
        seen_slots.add(entry["subject_slot"])
        seen_attachment_ids.add(aid)
    return {"state": "ATTACHMENT_RECEIPT_STRUCTURALLY_VALID",
            "provider_invocation_id": provider_receipt["provider_invocation_id"],
            "provider_evidence_id": provider_receipt["provider_evidence_id"],
            "attachments": len(entries), "generation_eligible": False,
            "visual_qa_passed": False,
            "note": "Structural receipt check only; provider provenance and actual invocation require independent corroboration."}
